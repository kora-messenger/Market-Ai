package com.veltravia.marketscopeai

import java.util.Locale

/**
 * Lightweight localization layer.
 *
 * The app follows the device language automatically: whatever the user's
 * phone is set to (German, Spanish, French, Portuguese, Italian, ...) the
 * UI strings covered by the dictionaries below switch to that language.
 * Anything not yet translated falls back to English, so coverage can grow
 * screen by screen without breaking anything.
 *
 * Usage in Compose: Text(t("Continue with Google"))
 * The dictionary key is always the exact English source string.
 */
object L10n {

    /** Two-letter device language, e.g. "de", lowercased; "en" when unknown. */
    val language: String = runCatching {
        Locale.getDefault().language.lowercase()
    }.getOrDefault("en")

    /** Full BCP-47 tag of the device locale, e.g. "de-DE" — sent to the backend so AI output follows the user's language. */
    val languageTag: String = runCatching {
        Locale.getDefault().toLanguageTag()
    }.getOrDefault("en")

    private val dictionaries: Map<String, Map<String, String>> = mapOf(
        "de" to de,
        "es" to es,
        "fr" to fr,
        "pt" to pt,
        "it" to it
    )

    fun t(en: String): String = dictionaries[language]?.get(en) ?: en
}

/** Shorthand used across screens. */
fun t(en: String): String = L10n.t(en)

